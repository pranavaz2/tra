class UserResponse(BaseModel):
    """
    Authenticated user summary embedded in the login response.

    Returned as the `user` field in LoginResponse. Provides only the fields
    the client needs immediately after login — not the full user profile.
    """

    model_config = ConfigDict(populate_by_name=True)

    user_id: Annotated[
        str,
        Field(description="Stable UUID identifying the authenticated user account."),
    ]

    email: Annotated[
        str,
        Field(
            description=(
                "Normalised (lowercase, stripped) email address. "
                "Display this value to the user, not the raw value they typed."
            ),
        ),
    ]

    is_email_verified: Annotated[
        bool,
        Field(
            description=(
                "True if the user has verified their email address. "
                "Always True on a successful login when email verification is required."
            ),
        ),
    ]


class LoginResponse(BaseModel):
    """
    POST /api/v1/auth/login 200 response body (the `data` field).

    Always issued on a successful login — all token fields are present.
    Unlike RegisterResponse, there is no conditional shape: a successful
    login always creates a session and always issues tokens.

    Client integration:
      - Store `refresh_token` in Flutter Secure Storage. Keep `access_token`
        in memory only — never persist it.
      - Replace both tokens on every successful POST /refresh call.
      - Use `access_token_expires_at` to proactively refresh before expiry.
      - Display `user.email` (server-normalised), not the raw user input.
    """

    model_config = ConfigDict(populate_by_name=True)

    access_token: Annotated[
        str,
        Field(
            description=(
                "JWT access token (15-minute lifetime). "
                "Store in memory only — never persist to disk or logs."
            ),
        ),
    ]

    refresh_token: Annotated[
        str,
        Field(
            description=(
                "Opaque refresh token (7-day lifetime). "
                "Store in Flutter Secure Storage. "
                "Immediately replace on every successful POST /refresh call."
            ),
        ),
    ]

    token_type: Annotated[
        str,
        Field(
            examples=["Bearer"],
            description='Token type. Always "Bearer".',
        ),
    ]

    access_token_expires_at: Annotated[
        datetime,
        Field(description="ISO 8601 UTC timestamp when the access token expires."),
    ]

    refresh_token_expires_at: Annotated[
        datetime,
        Field(description="ISO 8601 UTC timestamp when the refresh token expires."),
    ]

    session: Annotated[
        SessionResponse,
        Field(description="Summary of the newly created session."),
    ]

    user: Annotated[
        UserResponse,
        Field(description="Authenticated user summary."),
    ]



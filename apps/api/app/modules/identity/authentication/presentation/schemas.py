class LoginRequest(BaseModel):
    """
    POST /api/v1/auth/login request body.

    Transport-level validation enforced here:
      - email: non-empty, max 254 characters, whitespace stripped.
      - password: non-empty, max 128 characters (hard cap; prevents
        algorithmic-complexity attacks on the hashing layer).
      - device_info: optional nested object (same shape as registration).
      - locale: optional BCP 47 locale tag for localised error messages.
      - timezone: optional IANA timezone name for timezone-aware responses.

    Business validation NOT performed here (application layer handles these):
      - Email format / RFC 5322 compliance → InvalidEmailError (422)
      - Credential correctness → InvalidCredentialsError (401)
      - Account state → AccountLockedError (423) / AccountDisabledError (403)
      - Email verification → EmailNotVerifiedError (403)
    """

    model_config = ConfigDict(str_strip_whitespace=True)

    email: Annotated[
        str,
        Field(
            min_length=1,
            max_length=254,
            description=(
                "The user's registered email address. "
                "Normalised (lowercased and stripped) server-side before lookup."
            ),
            examples=["alice@example.com"],
        ),
    ]

    password: Annotated[
        str,
        Field(
            min_length=1,
            max_length=128,
            description=(
                "Account password in plaintext (sent over TLS). "
                "Never logged, stored in logs, or echoed in any response."
            ),
        ),
    ]

    device_info: Annotated[
        DeviceInfoRequest | None,
        Field(
            default=None,
            description=(
                "Optional device metadata for session display. "
                "Used to populate the session's device_name in session lists."
            ),
        ),
    ] = None

    locale: Annotated[
        str | None,
        Field(
            default=None,
            max_length=35,
            description=(
                "BCP 47 locale tag (e.g. 'en-US', 'fr-FR'). "
                "Overrides Accept-Language for localised server responses."
            ),
            examples=["en-US"],
        ),
    ] = None

    timezone: Annotated[
        str | None,
        Field(
            default=None,
            max_length=50,
            description=(
                "IANA timezone name (e.g. 'America/New_York'). "
                "Used for timezone-aware timestamps in responses."
            ),
            examples=["America/New_York"],
        ),
    ] = None



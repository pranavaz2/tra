class RegisterResponse(BaseModel):
    """
    POST /api/v1/auth/register 201 response body (the `data` field).

    Two variants, distinguished by `requires_verification`:

    **Production (requires_verification: true):**
    The account is created but email is unverified. No tokens are issued.
    Token fields (access_token, refresh_token, etc.) are absent.
    The user must complete `POST /verify-email` before logging in.

    **Dev / CI (requires_verification: false):**
    Email is auto-verified by server configuration. Tokens are issued
    immediately — same shape as the `POST /login` response.
    The client should navigate to the home screen using the returned tokens.

    This matches Authentication API Contract §5.1.
    """

    model_config = ConfigDict(populate_by_name=True)

    user_id: Annotated[
        str,
        Field(description="Stable UUID identifying the new user account."),
    ]

    email: Annotated[
        str,
        Field(
            description=(
                "Normalised (lowercase, stripped) email address. "
                "Display this value to the user, not the raw value they typed."
            ),
        ),
    ]

    requires_verification: Annotated[
        bool,
        Field(
            description=(
                "True: email not yet verified; no tokens issued; show 'check your email' screen. "
                "False: tokens issued immediately; navigate to home screen."
            ),
        ),
    ]

    message: Annotated[
        str | None,
        Field(
            default=None,
            description=(
                "Human-readable status message for display. "
                "Present when requires_verification is True."
            ),
        ),
    ] = None

    # ── Token fields (populated only when requires_verification is False) ── #

    access_token: Annotated[
        str | None,
        Field(
            default=None,
            description=(
                "JWT access token (15-minute lifetime). "
                "Store in memory only — never persist to disk. "
                "Dev/CI environments only."
            ),
        ),
    ] = None

    refresh_token: Annotated[
        str | None,
        Field(
            default=None,
            description=(
                "Opaque refresh token (7-day lifetime). "
                "Store in Flutter Secure Storage. "
                "Immediately replace on every successful POST /refresh call. "
                "Dev/CI environments only."
            ),
        ),
    ] = None

    token_type: Annotated[
        str | None,
        Field(
            default=None,
            examples=["Bearer"],
            description='Always "Bearer" when present.',
        ),
    ] = None

    access_token_expires_at: Annotated[
        datetime | None,
        Field(
            default=None,
            description="ISO 8601 UTC timestamp when the access token expires.",
        ),
    ] = None

    refresh_token_expires_at: Annotated[
        datetime | None,
        Field(
            default=None,
            description="ISO 8601 UTC timestamp when the refresh token expires.",
        ),
    ] = None

    session: Annotated[
        SessionResponse | None,
        Field(
            default=None,
            description=(
                "Session summary. "
                "Populated only when requires_verification is False."
            ),
        ),
    ] = None

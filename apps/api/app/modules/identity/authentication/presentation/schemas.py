"""
Pydantic v2 schemas for the Authentication presentation layer.

These schemas perform TRANSPORT-LEVEL validation only:
  - Type coercion and whitespace stripping
  - Field presence and maximum length (hard transport caps)
  - Enum membership for enumerated fields (e.g. platform)

They do NOT perform BUSINESS validation:
  - Email format and MX record validity → Email value object (domain layer)
  - Password strength → PasswordStrengthPolicy (application layer)
  - Email uniqueness → AuthenticationRepository (infrastructure layer)

Any business rule here would duplicate domain logic and create an
inconsistency surface — the API layer would reject before the domain
can produce a structured error response.

Schema → OpenAPI mapping:
  All schemas are generated by FastAPI into the /openapi.json document.
  Field descriptions, examples, and constraints feed directly into
  the Swagger UI and ReDoc documentation. Keep them accurate.
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Generic, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field

T = TypeVar("T")


# ──────────────────────────────────────────────────────────────────────────── #
# Generic response envelope                                                      #
# ──────────────────────────────────────────────────────────────────────────── #


class DataEnvelope(BaseModel, Generic[T]):
    """
    Standard single-resource success envelope.

    All success responses from the Authentication API are wrapped in::

        { "data": <payload> }

    This shape matches the Authentication API Contract §3.1.
    """

    model_config = ConfigDict(populate_by_name=True)

    data: T


# ──────────────────────────────────────────────────────────────────────────── #
# Shared sub-schemas                                                            #
# ──────────────────────────────────────────────────────────────────────────── #


class DeviceInfoRequest(BaseModel):
    """
    Optional device metadata sent with registration or login requests.

    Used to populate the AuthenticationSession for session-management
    display (e.g., "Alice's iPhone 15 Pro" in a devices list).

    All fields are optional. Omitting this object is valid.
    Transport caps are enforced; values beyond the cap are rejected with 422.
    """

    model_config = ConfigDict(str_strip_whitespace=True, extra="ignore")

    device_name: Annotated[
        str | None,
        Field(
            default=None,
            max_length=100,
            description="Human-readable device name. Shown in session management screens.",
            examples=["Alice's iPhone 15 Pro"],
        ),
    ] = None

    platform: Annotated[
        Literal["ios", "android", "web"] | None,
        Field(
            default=None,
            description='Client platform. One of: "ios", "android", "web".',
        ),
    ] = None

    app_version: Annotated[
        str | None,
        Field(
            default=None,
            max_length=20,
            description='Semver app version string (e.g. "1.0.0").',
            examples=["1.0.0"],
        ),
    ] = None

    os_version: Annotated[
        str | None,
        Field(
            default=None,
            max_length=50,
            description='Operating system version string (e.g. "iOS 17.4").',
            examples=["iOS 17.4"],
        ),
    ] = None


class SessionResponse(BaseModel):
    """
    Session summary embedded in token responses.

    Returned only when a session was created (dev/CI with auto-verify,
    or production after email is verified). Matches §3.4 of the API contract.
    """

    model_config = ConfigDict(populate_by_name=True)

    session_id: Annotated[
        str,
        Field(description="UUID identifying the newly created session."),
    ]
    device_name: Annotated[
        str | None,
        Field(
            description=(
                "Device name provided in the request. Null if not supplied."
            )
        ),
    ]
    created_at: Annotated[
        datetime,
        Field(description="ISO 8601 UTC timestamp when the session was created."),
    ]


# ──────────────────────────────────────────────────────────────────────────── #
# POST /register — Request schema                                                #
# ──────────────────────────────────────────────────────────────────────────── #


class RegisterRequest(BaseModel):
    """
    POST /api/v1/auth/register request body.

    Transport-level validation enforced here:
      - email: non-empty, max 254 characters (RFC 5321 limit), whitespace stripped.
      - password: non-empty, max 128 characters (hard cap; prevents
        algorithmic-complexity attacks on the hashing layer).
      - device_info: optional nested object.

    Business validation NOT performed here (application layer handles these):
      - Email format / RFC 5322 compliance → InvalidEmailError (422)
      - Password strength → WeakPasswordError (422)
      - Email uniqueness → EmailAlreadyExistsError (409)
    """

    model_config = ConfigDict(str_strip_whitespace=True)

    email: Annotated[
        str,
        Field(
            min_length=1,
            max_length=254,
            description=(
                "The user's email address. "
                "Normalised (lowercased and stripped) server-side before storage. "
                "Display the server-returned email value, not the raw user input."
            ),
            examples=["alice@example.com"],
        ),
    ]

    password: Annotated[
        str,
        Field(
            min_length=1,
            max_length=128,
            description=(
                "Account password in plaintext (sent over TLS). "
                "Strength requirements are enforced server-side (12–128 characters). "
                "Never logged, stored, or echoed."
            ),
        ),
    ]

    device_info: Annotated[
        DeviceInfoRequest | None,
        Field(
            default=None,
            description=(
                "Optional device metadata for session display. "
                "Ignored when no session is created (verification required)."
            ),
        ),
    ] = None


